"""io5 Job 1 report: global input ablation of three IO gap-fillers (val, all 1,458 days). Reads results/<run>.json (score_abl.py); writes
results/job1_table.csv, results/job1_summary.json, results/job1_tables.md and figures/job1_{heatmap_mean,bars,dist_bins}.png.

Run names: baseline io5_eval_<model>_base; ablation io5_eval_abl_<model>_<group>_<mode> (queue ~/mind_the_chl_gap/logs/io5/queue.sh).
Usage (project root): python -m analyses.io5_ablation.report_job1
"""
import csv
import json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import SymLogNorm

from chl_cnn.plotting import OKABE_ITO, ERR_CMAP

HERE = Path(__file__).resolve().parent
RES, FIG = HERE / "results", HERE / "figures"
MODELS = [("conv", "conv ±4 (t3d_dil_c4_60ep_gdl100)"), ("ptok4", "patch tokens, arm A (io3_ptok4)"), ("tdb", "token decoder + blend (io4_tokdec_blend)")]
PHYS = ["sst", "so", "mlotst", "sla", "currents", "winds", "air_temp", "physics"]
OTHER = ["ctx_chl", "day_chl", "clim", "clim_static", "latlon", "depth", "year"]
LABEL = {"sst": "SST", "so": "salinity", "mlotst": "MLD", "sla": "SLA", "currents": "currents (u, v)", "winds": "winds (u, v)",
         "air_temp": "air temp", "physics": "all 9 physics", "ctx_chl": "context-day CHL", "day_chl": "day-t CHL",
         "clim": "DOY clim (all paths)", "clim_static": "DOY clim (static ch only)", "latlon": "lat/lon", "depth": "depth", "year": "year"}
DIST = ["1", "2-3", "4-7", "8-15", "16+"]
AGE = ["1 d", "2-3 d", "4-8 d", "none"]


def load(run):
    p = RES / f"{run}.json"
    return json.loads(p.read_text()) if p.exists() else None


def collect():
    rows, base = [], {}
    for m, _ in MODELS:
        b = load(f"io5_eval_{m}_base")
        if b is None:
            continue
        base[m] = b["val"]
        for g in PHYS + OTHER:
            for mode in (("mean", "doyclim") if g in PHYS else ("mean",)):
                r = load(f"io5_eval_abl_{m}_{g}_{mode}")
                if r is None:
                    continue
                v, bv = r["val"], b["val"]
                rows.append(dict(model=m, group=g, mode=mode, dmae=v["mae"] - bv["mae"], mae=v["mae"], base_mae=bv["mae"], rmse=v["rmse"],
                                 drmse=v["rmse"] - bv["rmse"], bias=v["bias"], dbias=v["bias"] - bv["bias"],
                                 grad_ratio1=v["grad"]["1"]["ratio"], grad_corr1=v["grad"]["1"]["corr"],
                                 dgrad_ratio1=v["grad"]["1"]["ratio"] - bv["grad"]["1"]["ratio"], dgrad_corr1=v["grad"]["1"]["corr"] - bv["grad"]["1"]["corr"],
                                 **{f"ddist_{k}": v["by_dist"][k]["mae"] - bv["by_dist"][k]["mae"] for k in DIST},
                                 **{f"dage2_{k}": v["by_age2"][k]["mae"] - bv["by_age2"][k]["mae"] for k in AGE},
                                 n_hidden=v["n_hidden"], n_days=v["n_days"], n_nonfinite=v["n_nonfinite"], n_grad_pairs=v["grad"]["1"]["n_pairs"],
                                 check_passed=(r.get("ablate_info") or {}).get("check", {}).get("passed"),
                                 frac_changed=(r.get("ablate_info") or {}).get("check", {}).get("frac_values_changed_in_ablated_slots")))
    return rows, base


def get(rows, m, g, mode, k="dmae"):
    for r in rows:
        if (r["model"], r["group"], r["mode"]) == (m, g, mode):
            return r[k]
    return None


def f(x, nd=4, sign=True):
    return "-" if x is None else (f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}")


def tables_md(rows, base):
    ms = [m for m, _ in MODELS if m in base]
    L = ["# io5 Job 1: global input ablation, val (generated by analyses/io5_ablation/report_job1.py)", ""]
    L += ["Val hidden-px MAE (ln CHL) of each model with one input group replaced, minus the same model's unablated val MAE. "
          f"Every row: {base[ms[0]]['n_days']} val days, {base[ms[0]]['n_hidden']:,} hidden px.", ""]
    L += ["## Unablated baselines (eval-only reproduction)", "", "| model | val MAE | RMSE | bias | grad ratio / corr lag 1 | n days | n hidden px |", "|---|---|---|---|---|---|---|"]
    for m, lab in MODELS:
        if m in base:
            b = base[m]
            L.append(f"| {lab} | {b['mae']:.6f} | {b['rmse']:.4f} | {b['bias']:+.4f} | {b['grad']['1']['ratio']:.3f} / {b['grad']['1']['corr']:.3f} | {b['n_days']} | {b['n_hidden']:,} |")
    for mode in ("mean", "doyclim"):
        groups = PHYS + (OTHER if mode == "mean" else [])
        L += ["", f"## ΔMAE, {'training-mean' if mode == 'mean' else 'DOY-climatology'} replacement", "",
              "| group | " + " | ".join(m for m in ms) + " |", "|---|" + "---|" * len(ms)]
        for g in groups:
            L.append(f"| {LABEL[g]} | " + " | ".join(f(get(rows, m, g, mode)) for m in ms) + " |")
    for m, lab in MODELS:
        if m not in base:
            continue
        L += ["", f"## {lab}: all metrics", "",
              "| group | mode | ΔMAE | MAE | ΔRMSE | Δbias | grad ratio / corr lag 1 (Δ) | non-finite | n hidden px |", "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["model"] == m:
                L.append(f"| {LABEL[r['group']]} | {r['mode']} | {f(r['dmae'])} | {r['mae']:.4f} | {f(r['drmse'])} | {f(r['dbias'])} | "
                         f"{r['grad_ratio1']:.3f} / {r['grad_corr1']:.3f} ({f(r['dgrad_ratio1'], 3)} / {f(r['dgrad_corr1'], 3)}) | {r['n_nonfinite']} | {r['n_hidden']:,} |")
        b = base[m]
        L += ["", f"ΔMAE by bin ({lab}); bin n (hidden px): distance " + ", ".join(f"{k} px {b['by_dist'][k]['n']:,}" for k in DIST)
              + "; two-sided age " + ", ".join(f"{k} {b['by_age2'][k]['n']:,}" for k in AGE), "",
              "| group | mode | " + " | ".join(f"dist {k}" for k in DIST) + " | " + " | ".join(f"age {k}" for k in AGE) + " |",
              "|---|---|" + "---|" * (len(DIST) + len(AGE))]
        for r in rows:
            if r["model"] == m:
                L.append(f"| {LABEL[r['group']]} | {r['mode']} | " + " | ".join(f(r[f'ddist_{k}']) for k in DIST) + " | "
                         + " | ".join(f(r[f'dage2_{k}']) for k in AGE) + " |")
    bad = [r for r in rows if not r["check_passed"] or r["n_nonfinite"]]
    L += ["", f"Checks: {len(rows)} ablation evals; first-batch input check passed on {sum(bool(r['check_passed']) for r in rows)}; "
          f"rows with non-finite predictions on hidden px: {sum(r['n_nonfinite'] > 0 for r in rows)}" + (f" ({[(r['model'], r['group'], r['mode']) for r in bad]})" if bad else "")]
    return "\n".join(L) + "\n"


def fig_heatmap(rows, ms):
    groups = PHYS + OTHER
    M = np.full((len(ms), len(groups)), np.nan)
    for i, m in enumerate(ms):
        for j, g in enumerate(groups):
            v = get(rows, m, g, "mean")
            M[i, j] = np.nan if v is None else v
    lim = np.nanmax(np.abs(M))
    fig, ax = plt.subplots(figsize=(15, 3.6))
    im = ax.imshow(M, cmap=ERR_CMAP + "_r", norm=SymLogNorm(linthresh=1e-3, vmin=-lim, vmax=lim), aspect="auto")
    for i in range(len(ms)):
        for j in range(len(groups)):
            if np.isfinite(M[i, j]):
                ax.text(j, i, f"{M[i, j]:+.4f}", ha="center", va="center", fontsize=8)
    ax.set_xticks(range(len(groups)), [LABEL[g] for g in groups], rotation=35, ha="right")
    ax.set_yticks(range(len(ms)), [dict(MODELS)[m] for m in ms])
    fig.colorbar(im, ax=ax, label="ΔMAE vs unablated, ln CHL (symlog)")
    ax.set_title("Val hidden-px ΔMAE when one input group is replaced by its training mean (1,458 val days)")
    fig.tight_layout(); fig.savefig(FIG / "job1_heatmap_mean.png", dpi=120); plt.close(fig)


def fig_bars(rows, ms):
    fig, axs = plt.subplots(2, 2, figsize=(15, 9), gridspec_kw=dict(width_ratios=[1, 1]))
    w = 0.8 / len(ms)
    panels = [(axs[0, 0], PHYS, "mean", "Physics groups, training-mean replacement"), (axs[0, 1], PHYS, "doyclim", "Physics groups, DOY-climatology replacement"),
              (axs[1, 0], OTHER[:2], "mean", "CHL groups (value and visible mask set to 0)"), (axs[1, 1], OTHER[2:], "mean", "Static channels, training-mean replacement")]
    for ax, groups, mode, ttl in panels:
        x = np.arange(len(groups))
        for i, m in enumerate(ms):
            v = [get(rows, m, g, mode) for g in groups]
            ax.bar(x + (i - (len(ms) - 1) / 2) * w, [np.nan if a is None else a for a in v], w, color=OKABE_ITO[i], label=dict(MODELS)[m])
        ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(x, [LABEL[g] for g in groups], rotation=25, ha="right")
        ax.set(ylabel="val ΔMAE vs unablated (ln CHL)", title=ttl); ax.grid(alpha=.3, axis="y")
    axs[0, 0].legend(fontsize=8)
    fig.suptitle("Val hidden-px ΔMAE by ablated input group, three models (1,458 val days)")
    fig.tight_layout(); fig.savefig(FIG / "job1_bars.png", dpi=120); plt.close(fig)


def fig_dist(rows, ms, top):
    fig, axs = plt.subplots(1, len(ms), figsize=(5.2 * len(ms), 4.2), sharey=True, squeeze=False)
    for ax, m in zip(axs[0], ms):
        for k, g in enumerate(top):
            v = [get(rows, m, g, "mean", f"ddist_{d}") for d in DIST]
            ax.plot(range(len(DIST)), [np.nan if a is None else a for a in v], "o-", color=OKABE_ITO[k], label=LABEL[g])
        ax.set_xticks(range(len(DIST)), DIST); ax.set_yscale("symlog", linthresh=1e-3)
        ax.set(xlabel="distance of hidden px to nearest visible px (px)", ylabel="val ΔMAE vs unablated (ln CHL, symlog)", title=dict(MODELS)[m])
        ax.grid(alpha=.3); ax.axhline(0, color="k", lw=0.6)
    axs[0, 0].legend(fontsize=8)
    fig.suptitle("Val ΔMAE by distance bin for the 4 groups with the largest mean ΔMAE (training-mean replacement)")
    fig.tight_layout(); fig.savefig(FIG / "job1_dist_bins.png", dpi=120); plt.close(fig)


def main():
    FIG.mkdir(exist_ok=True)
    rows, base = collect()
    ms = [m for m, _ in MODELS if m in base]
    with open(RES / "job1_table.csv", "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(rows[0])); wr.writeheader(); wr.writerows(rows)
    avg = {g: np.mean([get(rows, m, g, "mean") for m in ms if get(rows, m, g, "mean") is not None]) for g in PHYS + OTHER
           if any(get(rows, m, g, "mean") is not None for m in ms)}
    top = sorted(avg, key=lambda g: -avg[g])[:4]
    (RES / "job1_tables.md").write_text(tables_md(rows, base))
    (RES / "job1_summary.json").write_text(json.dumps(dict(rows=rows, base={m: dict(mae=b["mae"], n_hidden=b["n_hidden"], n_days=b["n_days"]) for m, b in base.items()},
                                                           top4_mean=top, mean_dmae_over_models=avg), indent=1))
    fig_heatmap(rows, ms); fig_bars(rows, ms); fig_dist(rows, ms, top)
    print((RES / "job1_tables.md").read_text())
    print("figures:", *[FIG / f"job1_{k}.png" for k in ("heatmap_mean", "bars", "dist_bins")])


if __name__ == "__main__":
    main()
