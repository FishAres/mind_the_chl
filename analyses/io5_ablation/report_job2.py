"""io5 Job 2 report: physics loss (upwind, λ 0.3) on the io4_tokdec_blend recipe vs the λ 0 run. Reads both runs' history.json /
config.json and results/<run>.json (score_abl.py); writes results/job2_summary.json, results/job2_tables.md and
figures/job2_{val_curves,residual,bins}.png.

At 30 epochs only the per-epoch history exists (val MAE, RMSE, gradient ratio / corr at lag 1, residual |r|): the trainer keeps one
checkpoint (best val over epochs 11-60), so test, lags 2 / 4 and the bins are for that checkpoint only.
Usage (project root): python -m analyses.io5_ablation.report_job2
"""
import json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from chl_cnn.plotting import OKABE_ITO
from chl_cnn.runs import find_run

HERE = Path(__file__).resolve().parent
RES, FIG = HERE / "results", HERE / "figures"
NEW, OLD = "io5_tokdec_blend_up0p3", "io4_tokdec_blend"
LAB = {NEW: "token decoder + blend, λ 0.3 (io5)", OLD: "token decoder + blend, λ 0 (io4)", "io3_ptok4": "io3_ptok4 (arm A, λ 0)",
       "t3d_dil_c4_60ep_gdl100": "conv ±4 seed 0 (λ 0)"}
COL = {NEW: OKABE_ITO[3], OLD: OKABE_ITO[4], "io3_ptok4": OKABE_ITO[1], "t3d_dil_c4_60ep_gdl100": OKABE_ITO[0]}
DIST = ["1", "2-3", "4-7", "8-15", "16+"]
AGE = ["1 d", "2-3 d", "4-8 d", "none"]


def hist(run):
    return json.loads((find_run(run) / "history.json").read_text())


def best(h, lo, hi):
    v = np.array(h["val"][lo - 1:hi], dtype=float)
    i = int(np.nanargmin(v))
    ep = lo + i
    return dict(epoch=ep, val=float(v[i]), **{k: h[k][ep - 1] for k in ("val_rmse", "val_grad_ratio", "val_grad_corr", "val_phys_cloud", "val_phys_obs",
                                                                         "train", "train_phys", "lam")})


def main():
    FIG.mkdir(exist_ok=True)
    H = {r: hist(r) for r in (NEW, OLD, "io3_ptok4", "t3d_dil_c4_60ep_gdl100")}
    S = {r: json.loads((RES / f"{r}.json").read_text()) for r in (NEW, OLD)}
    C = {r: json.loads((find_run(r) / "config.json").read_text()) for r in (NEW, OLD)}
    out = dict(runs={})
    for r in (NEW, OLD):
        out["runs"][r] = dict(best_11_30=best(H[r], 11, 30), best_11_60=best(H[r], 11, min(60, len(H[r]["val"]))), n_epochs=len(H[r]["val"]),
                              selected_epoch=C[r]["best_epoch"], s_per_epoch=float(np.median(H[r]["epoch_s"])), peak_gpu_gb=C[r]["peak_gpu_gb"],
                              peak_gpu_reserved_gb=C[r]["peak_gpu_reserved_gb"],
                              val=S[r]["val"], test=S[r]["test"], physics=S[r]["trainer_physics"])
    (RES / "job2_summary.json").write_text(json.dumps(out, indent=1))

    o = out["runs"]
    L = ["# io5 Job 2: physics loss λ 0.3 vs λ 0, token decoder + blend recipe (generated by analyses/io5_ablation/report_job2.py)", ""]
    v0 = S[OLD]["val"]
    L += [f"Val n: {v0['n_days']} days, {v0['n_hidden']:,} hidden px; test n: {S[OLD]['test']['n_days']} days, {S[OLD]['test']['n_hidden']:,} hidden px. "
          f"Residual |r| (upwind form, ln CHL / day): val px-days under real clouds {S[OLD]['trainer_physics']['val']['n_cloud']:,}, "
          f"observed {S[OLD]['trainer_physics']['val']['n_obs']:,}.", ""]
    L += ["## Per-epoch history at the best val epoch (val only)", "",
          "| run | window | best epoch | val MAE | val RMSE | grad ratio / corr lag 1 | val mean abs r cloud / obs | train data / phys loss | n epochs |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in (NEW, OLD):
        for w in ("best_11_30", "best_11_60"):
            b = o[r][w]
            L.append(f"| {LAB[r]} | {w[5:].replace('_', '-')} | {b['epoch']} | {b['val']:.6f} | {b['val_rmse']:.4f} | {b['val_grad_ratio']:.3f} / {b['val_grad_corr']:.3f} | "
                     f"{b['val_phys_cloud']:.4f} / {b['val_phys_obs']:.4f} | {b['train']:.4f} / {b['train_phys']:.4f} | {o[r]['n_epochs']} |")
    L += ["", "## Selected checkpoint (best val over epochs 11-60), scored once", "",
          "| run | split | MAE | Δ vs λ 0 | RMSE | bias | grad ratio / corr lag 1 | lag 2 | lag 4 | mean abs r cloud / obs | n hidden px |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for sp in ("val", "test"):
        for r in (NEW, OLD):
            s = S[r][sp]; g = s["grad"]; ph = S[r]["trainer_physics"][sp]
            L.append(f"| {LAB[r]} | {sp} | {s['mae']:.6f} | {s['mae'] - S[OLD][sp]['mae']:+.6f} | {s['rmse']:.4f} | {s['bias']:+.4f} | "
                     f"{g['1']['ratio']:.3f} / {g['1']['corr']:.3f} | {g['2']['ratio']:.3f} / {g['2']['corr']:.3f} | {g['4']['ratio']:.3f} / {g['4']['corr']:.3f} | "
                     f"{ph['abs_r_cloud']:.4f} / {ph['abs_r_obs']:.4f} | {s['n_hidden']:,} |")
    L += ["", "## Val MAE by bin, selected checkpoints (Δ = λ 0.3 − λ 0)", "", "| bin | λ 0.3 MAE | λ 0 MAE | Δ | n hidden px |", "|---|---|---|---|---|"]
    for k in DIST:
        a, b = S[NEW]["val"]["by_dist"][k], S[OLD]["val"]["by_dist"][k]
        L.append(f"| distance {k} px | {a['mae']:.4f} | {b['mae']:.4f} | {a['mae'] - b['mae']:+.4f} | {b['n']:,} |")
    for key, nm in (("by_age2", "two-sided age"), ("by_age", "past-only age")):
        for k in AGE:
            a, b = S[NEW]["val"][key][k], S[OLD]["val"][key][k]
            L.append(f"| {nm} {k} | {a['mae']:.4f} | {b['mae']:.4f} | {a['mae'] - b['mae']:+.4f} | {b['n']:,} |")
    L += ["", f"Cost: λ 0.3 median {o[NEW]['s_per_epoch']:.0f} s/epoch, peak {o[NEW]['peak_gpu_gb']:.1f} GB allocated / {o[NEW]['peak_gpu_reserved_gb']:.1f} GB reserved; "
          f"λ 0 {o[OLD]['s_per_epoch']:.0f} s/epoch, {o[OLD]['peak_gpu_gb']:.1f} / {o[OLD]['peak_gpu_reserved_gb']:.1f} GB. "
          f"Non-finite predictions on hidden px (val / test): λ 0.3 {S[NEW]['val']['n_nonfinite']} / {S[NEW]['test']['n_nonfinite']}."]
    (RES / "job2_tables.md").write_text("\n".join(L) + "\n")

    # figures
    fig, ax = plt.subplots(figsize=(8, 4.8))
    allv = []
    for r, h in H.items():
        ax.plot(range(1, len(h["val"]) + 1), h["val"], color=COL[r], lw=2 if r == NEW else 1.2, label=LAB[r]); allv += h["val"][10:]
    ax.set_ylim(min(allv) * 0.99, min(allv) * 1.25)
    ax.axvspan(0.5, 10.5, color="0.9", zorder=0, label="epochs 1-10 (not eligible for selection)")
    ax.set(xlabel="epoch", ylabel="val hidden-px MAE (ln CHL)", title="Val MAE by epoch, physics loss λ 0.3 vs λ 0 and references (1,458 val days)")
    ax.grid(alpha=.3); ax.legend(fontsize=8); fig.tight_layout(); fig.savefig(FIG / "job2_val_curves.png", dpi=120); plt.close(fig)

    fig, axs = plt.subplots(1, 2, figsize=(12, 4.2))
    for ax, k, ttl in ((axs[0], "val_phys_cloud", "under real clouds"), (axs[1], "val_phys_obs", "on observed px")):
        for r in (NEW, OLD):
            ax.plot(range(1, len(H[r][k]) + 1), H[r][k], color=COL[r], label=LAB[r])
        ax.set(xlabel="epoch", ylabel="val mean |r| (ln CHL / day, upwind)", title=f"Val transport residual |r| {ttl}")
        ax.grid(alpha=.3)
    axs[0].legend(fontsize=8); fig.tight_layout(); fig.savefig(FIG / "job2_residual.png", dpi=120); plt.close(fig)

    fig, axs = plt.subplots(1, 2, figsize=(12, 4.2), sharey=True)
    for ax, key, bins, xl in ((axs[0], "by_dist", DIST, "distance to nearest visible px (px)"), (axs[1], "by_age2", AGE, "two-sided age of nearest real obs")):
        d = [S[NEW]["val"][key][k]["mae"] - S[OLD]["val"][key][k]["mae"] for k in bins]
        ax.bar(range(len(bins)), d, color=OKABE_ITO[3]); ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(range(len(bins)), bins); ax.set(xlabel=xl, ylabel="val MAE, λ 0.3 − λ 0 (ln CHL)", title=f"Val ΔMAE by {'distance' if key == 'by_dist' else 'age'} bin")
        ax.grid(alpha=.3, axis="y")
    fig.suptitle("Physics loss λ 0.3 minus λ 0, selected checkpoints, by bin"); fig.tight_layout(); fig.savefig(FIG / "job2_bins.png", dpi=120); plt.close(fig)
    print((RES / "job2_tables.md").read_text())


if __name__ == "__main__":
    main()
